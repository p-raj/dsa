    def isValidSudoku(self, board: List[List[str]]) -> bool:
        rows = cols = len(board)
        state = {}
        for r in range(rows):
            state[str(r + 1)] = {
                "r": [False] * rows,
                "c": [False] * rows,
                "b": [False] * rows,
            }
        for r in range(rows):
            for c in range(cols):
                num_ = board[r][c]
                block = self.rc_to_b(r, c)
                if "." != num_:
                    if state[num_]["r"][r] or state[num_]["c"][c] or state[num_]["b"][block]:
                        return False
                    state[num_]["r"][r] = True
                    state[num_]["c"][c] = True
                    state[num_]["b"][block] = True
        return True
